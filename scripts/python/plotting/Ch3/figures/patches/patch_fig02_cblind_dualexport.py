"""
patch_fig02_cblind_dualexport.py — Fig 2 (sector map) cblind/dual-export pass.
================================================================================
Unlike Fig 1, this figure has no local hardcoded colors -- it draws sectors
entirely from ch3_config.SECTOR_COLORS, the SAME dict every other sector-
colored figure in the chapter imports (fig03, fig06-09, ch3_plot.sector_grid()).
Per Frida's explicit choice, this patch updates SECTOR_COLORS globally to a
colorblind-safe (Okabe & Ito 2008) set, rather than giving fig_sector_map.py
its own local override. That means every other sector-colored figure will
pick up the new colors the next time each one is individually rerun --
they are NOT touched or regenerated by this patch.

Does three things:
  1. ch3_config.py — SECTOR_COLORS' 6 values replaced with a colorblind-safe
     set. Idempotent (skips if already applied).
  2. fig_02_sector_map.py — turns on presentation=True on its one save() call.
  3. fig_02_sector_map.py — adds a DEPENDENCIES block to its module docstring
     (no CSV/table in, none out; only cartopy's Natural Earth shapefiles as
     an external input) and updates the Output: line for both exports, plus
     fixes the stale "python fig_sector_map.py" run command in the header.

ch3_plot.py needs no change here -- it already has the presentation=
parameter from the Fig 1 patch.

Run from figures/patches/: python3 patch_fig02_cblind_dualexport.py
Then: py_compile both files, git diff to review, run fig_02_sector_map.py.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FIGURES_DIR = os.path.dirname(HERE)  # patches/ -> figures/


def patch_file(relname, replacements, skip_if_present=None):
    path = os.path.join(FIGURES_DIR, relname)
    with open(path, "r", encoding="utf-8") as f:
        content = f.read()

    if skip_if_present is not None and skip_if_present in content:
        print(f"Skipping {relname} — already patched (found {skip_if_present!r}).")
        return

    for label, old, new in replacements:
        n = content.count(old)
        if n != 1:
            raise SystemExit(
                f"{relname}: expected exactly 1 match for {label!r}, found {n}. "
                "File has drifted from what this patch expects -- aborting "
                "without writing anything to this file. Diff it by hand."
            )
        content = content.replace(old, new, 1)

    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Patched {relname} ({len(replacements)} edit(s))")


# ── 1. ch3_config.py: SECTOR_COLORS -> colorblind-safe set ──────────────────
