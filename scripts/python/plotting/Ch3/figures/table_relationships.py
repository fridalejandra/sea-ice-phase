#!/usr/bin/env python3
"""
make_table3.py -- build Table 3 (tab:ch3_table3) straight from ch3_stats.py's
output tables, so its numbers are never copied by hand again.

Why: until 2026-10-04 Table 3 was typed in from an older draft table. Its
"shift p < 1e-5" for ASL-Ross came from a script that counted 1979-2018 twice
(FULL and HR2018 fits both kept), and its r / LOYO columns came from a
different fit file. Every row now comes from one ch3_stats.py run.

Reads   results/ch3/tables/t35_primary_pairs.csv     r, loo_worst_p   (full record)
        results/ch3/tables/t36_stationarity_2001.csv  r_pre, r_post, p_shift
Writes  results/ch3/tables/table3_rows.tex            the seven LaTeX rows
and compares them with the rows currently in ch3_main.tex.

    python make_table3.py                      # write rows file, report differences
    python make_table3.py --write              # also replace the rows in ch3_main.tex
    python make_table3.py --tex path/to/ch3_main.tex [--write]

Run after ch3_stats.py. --write keeps a copy as ch3_main.tex.bak.
"""
import os
import re
import sys
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from ch3_config import ROOT, TABLES_DIR, PRIMARY_PAIRS, SECTOR_LABELS

WRITE = "--write" in sys.argv

# Row order and wording as they appear in the manuscript
ROWS = [  # (index code, sector code, target, index label, sector label, component label)
    ("Nino34_SON",    "SIE_Amundsen_Bellingshausen", "amplitude_raw_anom", "Niño3.4 (SON)",    "Amundsen--Bellingshausen", "Amplitude"),
    ("Nino34_annual", "SIE_King_Haakon",             "amplitude_raw_anom", "Niño3.4 (annual)", "King Haakon",              "Amplitude"),
    ("SAM_RET",       "SIE_East_Antarctica",         "max_doy_raw_anom",   "SAM (Oct--Jan)",   "East Antarctica",          "Day of maximum"),
    ("SAM_JJA",       "SIE_Weddell",                 "amplitude_raw_anom", "SAM (JJA)",        "Weddell Sea",              "Amplitude"),
    ("ASL_annual",    "SIE_Ross",                    "amplitude_raw_anom", "ASL (annual)",     "Ross Sea",                 "Amplitude"),
    ("ZW3R_SON",      "SIE_King_Haakon",             "max_doy_raw_anom",   "ZW3 (SON)",        "King Haakon",              "Day of maximum"),
    ("ZW3R_annual",   "SIE_Amundsen_Bellingshausen", "amplitude_raw_anom", "ZW3 (annual)",     "Amundsen--Bellingshausen", "Amplitude"),
]
assert {(s, t, i) for i, s, t, *_ in ROWS} == {(s, t, i) for s, t, i, _ in PRIMARY_PAIRS}, \
    "ROWS no longer matches ch3_config.PRIMARY_PAIRS -- update ROWS to the new pair list"


def r_fmt(r):
    return f"${r:+.2f}$"


def p_fmt(p, loyo=False):
    if p < 0.001:
        return "$<0.001$"
    if loyo or p < 0.01:
        return f"{p:.3f}"
    return f"{p:.2f}"


def load(name):
    path = os.path.join(TABLES_DIR, name)
    if not os.path.exists(path):
        sys.exit(f"{path} not found -- run ch3_stats.py first.")
    return pd.read_csv(path)


pp, st = load("t35_primary_pairs.csv"), load("t36_stationarity_2001.csv")
lines = []
for ic, sec, tv, ilab, slab, clab in ROWS:
    key = dict(sector=SECTOR_LABELS[sec], target=tv, index=ic)
    a = pp[(pp.sector == key["sector"]) & (pp.target == tv) & (pp["index"] == ic)]
    b = st[(st.sector == key["sector"]) & (st.target == tv) & (st["index"] == ic)]
    if len(a) != 1 or len(b) != 1:
        sys.exit(f"expected exactly one row for {key} in each table, got {len(a)} and {len(b)}")
    a, b = a.iloc[0], b.iloc[0]
    lines.append(f"    {ilab} & {slab} & {clab} & {r_fmt(a.r)} & {p_fmt(a.loo_worst_p, loyo=True)} & "
                 f"{r_fmt(b.r_pre)} / {r_fmt(b.r_post)} & {p_fmt(b.p_shift)}\\\\")

out = os.path.join(TABLES_DIR, "table3_rows.tex")
with open(out, "w") as f:
    f.write("% generated by make_table3.py from t35_primary_pairs.csv + t36_stationarity_2001.csv -- do not edit by hand\n")
    f.write("\n".join(lines) + "\n")
print(f"wrote {out}\n")
print("\n".join(lines))

# ── compare with / update ch3_main.tex ──────────────────────────────────────
tex = sys.argv[sys.argv.index("--tex") + 1] if "--tex" in sys.argv else None
if tex is None:
    hits = []
    for dp, dns, fns in os.walk(ROOT):
        dns[:] = [d for d in dns if d not in {".git", "archive", "node_modules"}]
        hits += [os.path.join(dp, f) for f in fns if f == "ch3_main.tex"]
    if len(hits) != 1:
        print(f"\n{'No' if not hits else len(hits)} ch3_main.tex found under {ROOT} -- pass --tex PATH to compare/update.")
        sys.exit(0)
    tex = hits[0]

s = open(tex, encoding="utf-8").read()
m = re.search(r"\n[ \t]*\\label\{tab:ch3_table3\}.*?\\midrule\n(.*?)\n[ \t]*\\bottomrule", s, re.S)
if not m:
    sys.exit(f"Couldn't find Table 3's \\midrule ... \\bottomrule block in {tex}")
current = [ln for ln in m.group(1).splitlines() if ln.strip() and not ln.strip().startswith("%")]
new = lines
norm = lambda x: re.sub(r"\s+", " ", x.strip())
diffs = [(c, n) for c, n in zip(current, new) if norm(c) != norm(n)]
if len(current) != len(new):
    diffs.append((f"<{len(current)} rows in tex>", f"<{len(new)} rows generated>"))

print(f"\n{tex}")
if not diffs:
    print("Table 3 in the manuscript already matches the ledger. Nothing to do.")
    sys.exit(0)
print(f"{len(diffs)} row(s) differ from the ledger:")
for c, n in diffs:
    print(f"  tex:    {c.strip()}\n  ledger: {n.strip()}\n")
if not WRITE:
    print("Run again with --write to replace them.")
    sys.exit(0)
with open(tex + ".bak", "w", encoding="utf-8") as f:
    f.write(s)
s = s[:m.start(1)] + "\n".join(new) + s[m.end(1):]
with open(tex, "w", encoding="utf-8") as f:
    f.write(s)
print(f"updated Table 3 in {tex} (previous version in {os.path.basename(tex)}.bak)")
